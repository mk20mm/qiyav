function adapt(source) {
  let output = source
    .replace(/<!--[^]*?-->/g, "")
    .replaceAll("/methodology/", "/method/")
    .replaceAll("/cases/bill-api", "/cases/ecosystem-gmv")
    .replaceAll("/tools/checklist", "/method/02-clarify")
    .replaceAll("/tools/spec-template", "/method/04-spec")
    .replaceAll("/tools/agent-task-template", "/method/09-agent-task")
    .replaceAll("/tools/verification-template", "/method/06-verify")
    .replaceAll("/tools/defect-library", "/method/13-defect-library")
    .replaceAll("尹庆", "QIYA");

  for (const [from, to] of phraseReplacements) output = output.replaceAll(from, to);

  return output
    .replaceAll("平台数据什么状态", "平台与日期参数是否有效")
    .replaceAll("平台数据用于", "GMV 结果用于")
    .replaceAll("平台数据、GMV 结果", "平台源数据、GMV 结果")
    .replaceAll("GMV 结果结果", "GMV 结果")
    .replaceAll("平台 GMV 生成入口入口", "平台 GMV 生成入口")
    .replace(/\n{4,}/g, "\n\n\n")
    .trim()
    .concat("\n");
}

